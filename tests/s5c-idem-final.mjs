import { api, login, register, uniqueEmail, orderBody, dataOf, orderIdOf, dbQuery, check, finish } from './api/lib.mjs';
const RUN = Date.now();
const TC = 'S5C-IDEM';
const row = dbQuery(`SELECT dish_id,(total_qty-reserved_qty-sold_qty) FROM dish_daily_stock WHERE serve_date='2026-11-15' AND (total_qty-reserved_qty-sold_qty)>=3 ORDER BY dish_id LIMIT 1`);
const dishId = Number(row[0][0]);
console.log('dish', dishId, 'available', row[0][1]);
const email = uniqueEmail('idem_final'); await register(email,'Abc12345'); const u = await login(email,'Abc12345');
const body = orderBody(dishId,{qty:1,deliveryDate:'2026-11-15',mealType:'Lunch'});
const key = `s5c-final-${RUN}`;
const conc = await Promise.all([0,1,2].map(()=>api('POST','/api/v1/orders',{token:u.token,key,body})));
const ser = await api('POST','/api/v1/orders',{token:u.token,key,body});
const all=[...conc,ser]; const ids=[...new Set(all.map(r=>orderIdOf(r.json)).filter(Boolean).map(String))];
check(TC,'同键 4 次（3 并发+1 串行）均 200/201',all.every(r=>[200,201].includes(r.status)),`statuses=${all.map(r=>r.status)} bodies=${all.map(r=>r.json?.code).join(',')}`);
check(TC,'同键仅 1 个 orderId',ids.length===1,`ids=${JSON.stringify(ids)}`);
const cnt=dbQuery(`SELECT COUNT(*) FROM orders WHERE idempotency_key='${key}'`);
check(TC,'DB 同键仅 1 单',Number(cnt[0][0])===1,`count=${cnt[0][0]}`);
const led=dbQuery(`SELECT entry_type,COUNT(*) FROM inventory_ledger WHERE order_id IN (SELECT id FROM orders WHERE idempotency_key='${key}') GROUP BY entry_type`);
check(TC,'同键仅 1 条 RESERVE',led.some(x=>/RESERVE/.test(x[0])&&Number(x[1])===1),JSON.stringify(led));
const email2=uniqueEmail('idem_final2'); await register(email2,'Abc12345'); const u2=await login(email2,'Abc12345');
const key2=`s5c-final2-${RUN}`;
const f=await api('POST','/api/v1/orders',{token:u2.token,key:key2,body});
check(TC,'异体前置首单 201',f.status===201,`status=${f.status} body=${f.text.slice(0,160)}`);
const c=await api('POST','/api/v1/orders',{token:u2.token,key:key2,body:{...body,items:[{...body.items[0],qty:2}]}});
check(TC,'同键异体 → 409 IDEMPOTENCY_CONFLICT',c.status===409&&/IDEMPOTENCY_CONFLICT/.test(c.text),`status=${c.status} body=${c.text.slice(0,160)}`);
finish('s5c-idem-final.json');
